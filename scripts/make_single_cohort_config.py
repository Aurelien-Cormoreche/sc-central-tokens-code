"""Write configs/train_single_cohort.yaml: train on one cohort, test on each of the others.

For each training cohort T (the 5 cohorts of configs/train_cross_cohort.yaml): train = T's
slides except its val donors; val = T's val donors, i.e. the val of the within-cohort configs
(T's val slides in train_cross_cohort.yaml; 10X, which has no within-cohort config, the same
way). A model may only know the cell types that both T and its test cohort contain
(make_cross_cohort_config.MISSING_TYPES), so the other cohorts are grouped by that label space
and each group is one split: one model, trained once and tested on every slide of the group's
cohorts. data.drop_classes_absent_from_test masks train and val to the types the test slides
contain, which is the group's label space; test cells of types T lacks are dropped as for any
class without train support. SPLIT and 10X get 3 splits (all types / no Malignant / no
Epithelial), VANNAN, MCCORD and JOHNSON 2 -- 12 in total. per_slide_metrics.csv's `cohort`
column separates a split's test cohorts.

Usage (repo root):
    python scripts/make_single_cohort_config.py [--splits-csv _metadata_work/splits.csv]
"""
import argparse
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_cross_cohort_config as cc  # noqa: E402
import make_within_cohort_configs as wc  # noqa: E402

REPO = cc.REPO


def _splits_block(rows: list[dict]) -> tuple[str, int]:
    slides = {cohort: sorted({cc._wsi_name(r["xenium_folder"]) for r in rows if r["source"] == source})
              for source, cohort in cc.COHORT_NAMES.items()}
    lines = [
        "# Scheme: train on one cohort, test on the others -- regenerate with",
        "# scripts/make_single_cohort_config.py. Per training cohort: train = its slides except",
        "# its val donors, val = those donors (as in configs/train_within_cohort_*.yaml). Test",
        "# cohorts sharing the label space a model may have (the types both cohorts contain) share",
        "# one split; data.drop_classes_absent_from_test masks train/val to it. Left out (no",
        f"# embeddings): {', '.join(sorted(cc.EXCLUDED_WSIS))}.",
        "splits:",
    ]
    i = 0
    for source, cohort in cc.COHORT_NAMES.items():
        donors, val_donors = wc._cohort_donors(rows, source)
        val = sorted(w for d in val_donors for w in donors[d])
        train = sorted(w for d in donors if d not in val_donors for w in donors[d])
        groups: dict[frozenset, list[str]] = defaultdict(list)
        for other in cc.COHORT_NAMES.values():
            if other != cohort:
                missing = cc.MISSING_TYPES.get(cohort, set()) | cc.MISSING_TYPES.get(other, set())
                groups[frozenset(missing)].append(other)
        for missing, tests in sorted(groups.items(), key=lambda kv: (len(kv[0]), sorted(kv[0]))):
            test = sorted(w for c in tests for w in slides[c])
            lines.append(
                f"  # split {i}: train = {cohort} ({len(train)} slides, val {len(val)}) -> test = "
                f"{'+'.join(tests)} ({len(test)} slides); "
                + (f"cell types without {', '.join(sorted(missing))}" if missing else "all cell types")
            )
            for j, (side, wsis) in enumerate((("train", train), ("val", val), ("test", test))):
                lines.append(f"  {'- ' if j == 0 else '  '}{side}:")
                lines.extend(f"      {w}: 1.0" for w in wsis)
            lines.append("")
            i += 1
    return "\n".join(lines) + "\n", i


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--splits-csv", type=Path, default=REPO / "_metadata_work" / "splits.csv")
    parser.add_argument("--out", type=Path, default=REPO / "configs" / "train_single_cohort.yaml")
    args = parser.parse_args()

    rows = wc._cross_cohort_rows(args.splits_csv)
    text = (REPO / "configs" / "train_cross_cohort.yaml").read_text()
    head, rest = text.split("# Scheme:", 1)
    _, tail = rest.split("# When true, the launcher also submits", 1)
    block, n_splits = _splits_block(rows)
    text = head + block + "\n# When true, the launcher also submits" + tail

    text = cc._replace_once(
        text,
        "# Leave-one-cohort-out (cross-cohort) classifier evaluation -- generated by\n"
        "# scripts/make_cross_cohort_config.py from configs/train.yaml; edit there or here.\n",
        "# Train on one cohort, test on the others -- generated by\n"
        "# scripts/make_single_cohort_config.py from configs/train_cross_cohort.yaml.\n",
    )
    text = cc._replace_once(text, "experiment: cross_cohort\n", "experiment: single_cohort\n")
    text = cc._replace_once(text, "  experiment_name: embeddings_eval_cross_cohort\n",
                            "  experiment_name: embeddings_eval_single_cohort\n")
    # Val is one cohort: cohort balancing would be a no-op (as in the within-cohort configs).
    text = cc._replace_once(
        text, "  selection_metric: cohort_balanced_slide_macro_f1\n", "  selection_metric: slide_macro_f1\n"
    )
    text = cc._replace_once(text, "  drop_classes_absent_from_test: false\n", "  drop_classes_absent_from_test: true\n")
    # Memory and the fixed 24 h stay as in train_cross_cohort.yaml: a split testing on SPLIT + 10X
    # loads ~13M cells, as many as a cross-cohort fold.

    args.out.write_text(text)
    print(f"wrote {args.out} ({n_splits} splits)")


if __name__ == "__main__":
    main()
