"""Write configs/scaling/train_cross_cohort_test_classes_frac{pp}_seed{s}.yaml: the masked
cross-cohort setting on all five leave-one-cohort-out folds, trained on a random fraction
of their train cells.

Folds are those of configs/train_cross_cohort.yaml (split_<i> holds out the same cohort:
0 SPLIT, 1 VANNAN, 2 MCCORD, 3 JOHNSON, 4 10X) with data.drop_classes_absent_from_test on,
i.e. each fold trains only on its test cohort's cell types. That is
train_cross_cohort_test_classes.yaml for VANNAN, MCCORD and JOHNSON, and a no-op for SPLIT
and 10X (every type present), whose 100% point is then cross_cohort's split 0 / 4.

One config per (fraction, seed). Every train slide keeps a seeded uniform random
`fraction` of its cells (the per-WSI proportion experiment.py already applies), so each
slide and, in expectation, each class keeps its share of the train set. Val and test stay
at 1.0: early stopping, model selection and evaluation see the same cells as the 100% run,
so only the amount of train data differs. The seed changes the train subset and the
classifier's init; the test set is the same for every seed (proportion 1.0, no
data.max_cells_per_wsi). Each config is its own experiment
(cross_cohort_test_classes_scaling_frac{pp}_seed{s}), so results, saved weights and SLURM
logs never collide. Everything else is copied from train_cross_cohort.yaml, so rerun this
script if it changes.

Usage (repo root):
    python scripts/make_scaling_configs.py [--fractions 0.05] [--seeds 42 43 44]
Then, per config (on the cluster):
    python -m src.python.classifier_training.launcher \
        --config-name=scaling/train_cross_cohort_test_classes_frac05_seed42 \
        data.model_name=UNI2 data.correction_name=raw
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_cross_cohort_config as cc  # noqa: E402

REPO = cc.REPO
SOURCE = "train_cross_cohort"
EXPERIMENT = "cross_cohort_test_classes"
# The 100% runs took ~1.3-2.3 h (load ~15 min); a fraction trains on fewer cells but loads the same.
TIME = "06:00:00"


def _tag(fraction: float) -> str:
    return f"frac{round(100 * fraction):02d}"


def _subsample_train(text: str, fraction: float) -> tuple[str, int]:
    """Set every train slide's proportion to `fraction` (val/test untouched); returns
    (text, number of train slide entries changed)."""
    out, side, n = [], None, 0
    for line in text.split("\n"):
        m = re.fullmatch(r"  (?:- |  )(train|val|test):", line)
        if m:
            side = m.group(1)
        elif side == "train" and re.fullmatch(r"      \S+: 1\.0", line):
            line = line[: -len("1.0")] + f"{fraction:g}"
            n += 1
        elif not line.startswith("      "):
            side = None
        out.append(line)
    return "\n".join(out), n


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fractions", type=float, nargs="+", default=[0.05])
    parser.add_argument("--seeds", type=int, nargs="+", default=[42, 43, 44])
    parser.add_argument("--out-dir", type=Path, default=REPO / "configs" / "scaling")
    args = parser.parse_args()
    assert all(0 < f <= 1 for f in args.fractions), args.fractions

    source = (REPO / "configs" / f"{SOURCE}.yaml").read_text()
    n_folds = len(re.findall(r"^  - train:$", source, flags=re.M))
    args.out_dir.mkdir(parents=True, exist_ok=True)

    for fraction in args.fractions:
        for seed in args.seeds:
            experiment = f"{EXPERIMENT}_scaling_{_tag(fraction)}_seed{seed}"
            text, n_train = _subsample_train(source, fraction)
            assert n_train and source.count(": 1.0\n") - n_train == text.count(": 1.0\n"), "train entries not found"

            # In a subfolder of configs/, Hydra would otherwise nest every key under `scaling`.
            text = cc._replace_once(
                text,
                "# Leave-one-cohort-out (cross-cohort) classifier evaluation -- generated by\n"
                "# scripts/make_cross_cohort_config.py from configs/train.yaml; edit there or here.\n",
                "# @package _global_\n"
                f"# Training-set scaling of the masked cross-cohort folds: {100 * fraction:g}% of every train\n"
                f"# slide's cells, seed {seed} -- generated by scripts/make_scaling_configs.py from\n"
                f"# configs/{SOURCE}.yaml (+ data.drop_classes_absent_from_test); edit there.\n"
                "# Val and test keep every cell.\n",
            )
            text = cc._replace_once(text, "seed: 42\n", f"seed: {seed}\n")
            text = cc._replace_once(text, "experiment: cross_cohort\n", f"experiment: {experiment}\n")
            text = cc._replace_once(
                text, "\nsplits:\n",
                f"\n# Train proportions: {fraction:g} (scripts/make_scaling_configs.py); val and test: 1.0.\nsplits:\n",
            )
            text = cc._replace_once(text, "  drop_classes_absent_from_test: false\n", "  drop_classes_absent_from_test: true\n")
            text = cc._replace_once(
                text, "  experiment_name: embeddings_eval_cross_cohort\n", f"  experiment_name: embeddings_eval_{experiment}\n"
            )
            text = cc._replace_once(text, '  time: "24:00:00"\n', f'  time: "{TIME}"\n')

            out = args.out_dir / f"train_{EXPERIMENT}_{_tag(fraction)}_seed{seed}.yaml"
            out.write_text(text)
            print(f"wrote {out.relative_to(REPO)} ({n_folds} folds, {n_train} train slide entries at {fraction:g})")


if __name__ == "__main__":
    main()
