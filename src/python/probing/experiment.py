"""
Layer 2 -- Probing experiment runner for one WSI split.

For one Leave-WSI-Out (LWO) split (train / val / test WSIs, see configs/
probing_colon.yaml's `splits`), loads the embedding-bearing cell population once,
then for every enabled probe (see src/python/probing/probes -- area, eccentricity,
orientation, cell_type_composition, cell_count, cell_density; set
cfg.probes.<name>.enabled=true/false to pick which ones run):

  1. computes that probe's ground-truth target for every cell (a Xenium boundary-
     polygon shape descriptor for the cell-level probes, or a cell_type_composition
     / cell_count / cell_density of a context_px-sized window around the cell for
     the context probes -- see geometry.py / data/cell_population.py),
  2. sweeps a ridge-regression regularization strength (lambda) fit in closed form
     on train (src/python/probing/solvers.py, src/python/probing/runner.py),
     selecting the best lambda by validation performance,
  3. evaluates the selected model on val and test, and
  4. writes the per-lambda sweep, a results summary, and a per-cell (true, pred)
     CSV for further analysis to outputs/.

Invoked by the SLURM jobs generated by launcher.py:
    python -m src.python.probing.experiment \\
        split_idx=0 data.model_name=UNI2 data.correction_name=Base
"""
from __future__ import annotations

