import sys
from pathlib import Path
from typing import Any, Optional

import mlflow
import numpy as np
import pandas as pd
import yaml
from omegaconf import DictConfig, OmegaConf

import hydra

from src.python.code_configs.mappings import mapping_factory
from src.python.probing.data.boundary_cache import BoundaryCache, BoundaryRoots
from src.python.probing.data.cell_population import PopulationCache, resolve_positions
from src.python.probing.data.embeddings_loader import load_probe_population
from src.python.probing.probes.base import PROBE_FACTORY_REGISTRY, Probe, ProbeContext
from src.python.probing.runner import run_probe
import src.python.probing.probes  # noqa: F401 -- side-effect: registers every built-in probe type


# ── helpers ──────────────────────────────────────────────────────────────────

# Mirrors classifier_training/experiment.py's identically-named helpers -- see
# that file's own comment: kept independently duplicated per-pipeline rather than
# imported, same convention classifier_training/grid_experiment.py already follows.
def _matching_folder_name(consider_matching: bool) -> str:
    return "matching" if consider_matching else "all_cells"


def _embeddings_folder_name(embeddings_datasets: list[str]) -> str:
    return "_".join(sorted(embeddings_datasets)) if embeddings_datasets else "default"


def _safe_dirname(name: str) -> str:
    """probe.name for a context probe looks like 'cell_type_composition@224px' --
    '@' is filesystem-safe on every platform this runs on, but swapped for '_'
    anyway purely for readability of the resulting path."""
    return name.replace("@", "_")


def _parse_wsi_ct_props(side) -> Optional[dict[str, dict[str, float]]]:
    raw = OmegaConf.select(side, "cell_type_proportions")
    if not raw:
        return None
    return {wsi: {ct: float(p) for ct, p in ct_map.items()} for wsi, ct_map in raw.items()}


def _wsi_props(side) -> dict[str, float]:
    return {k: float(v) for k, v in side.items() if k != "cell_type_proportions"}


def _build_active_probes(cfg: DictConfig) -> list[Probe]:
    """Reads cfg.probes.<key>.enabled for every registered probe type (see
    PROBE_FACTORY_REGISTRY / src/python/probing/probes/*.py's
    @register_probe_factory) and expands each enabled block into its Probe
    instance(s) -- one, or one per context_px for a context probe."""
    probes: list[Probe] = []
    probes_cfg = OmegaConf.select(cfg, "probes", default={}) or {}
    for key, block in probes_cfg.items():
        if not bool(OmegaConf.select(block, "enabled", default=False)):
            continue
        factory = PROBE_FACTORY_REGISTRY.get(key)
        if factory is None:
            raise ValueError(
                f"cfg.probes.{key} is enabled but no probe factory is registered under "
                f"that name -- known probe types: {sorted(PROBE_FACTORY_REGISTRY)}"
            )
        block_dict = OmegaConf.to_container(block, resolve=True)
        probes.extend(factory(block_dict))
    return probes


def _lambdas_for(probe: Probe, cfg: DictConfig) -> list[float]:
    probes_cfg = OmegaConf.select(cfg, "probes", default={}) or {}
    key = getattr(probe, "name_prefix", probe.name)
    block = probes_cfg.get(key)
    lambdas = OmegaConf.select(block, "lambdas", default=None) if block is not None else None
    if lambdas is None:
        lambdas = cfg.lambdas
    return [float(v) for v in lambdas]


# ── per-split cell context ──────────────────────────────────────────────────

def _build_context(
    embeddings: np.ndarray, cell_ids: np.ndarray, cell_types: np.ndarray, wsi_names: np.ndarray,
    boundary_cache: BoundaryCache, population_cache: PopulationCache,
) -> tuple[np.ndarray, ProbeContext]:
    x, y, position_valid = resolve_positions(cell_ids, wsi_names, population_cache)
    ctx = ProbeContext(cell_ids, wsi_names, cell_types, x, y, position_valid, boundary_cache, population_cache)
    return embeddings, ctx


# ── main experiment logic ─────────────────────────────────────────────────────

def run_split_experiment(split_idx: int, cfg: DictConfig, device: str, output_dir: Path) -> None:
    mapping = mapping_factory(cfg.mapping)
    base_path = os.path.join(cfg.data.base_dir, f"{cfg.data.model_name}_h5", cfg.data.correction_name)
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    consider_matching: bool = bool(OmegaConf.select(cfg, "data.consider_matching", default=True))
    seed = int(OmegaConf.select(cfg, "seed", default=42))
    rng = np.random.default_rng(seed)

    boundary_cache = BoundaryCache(
        BoundaryRoots(cfg.data.cell_boundaries_root, cfg.data.alignment_matrix_root),
        kind=str(OmegaConf.select(cfg, "data.boundary_kind", default="cell")),
    )
    population_cache = PopulationCache(cfg.data.cells_info_root, mapping)

    # ── data loading (mirrors classifier_training/experiment.py's split resolution) ──
    if split_idx == -1:
        all_wsi_props: dict[str, float] = {}
        all_ct_props: dict[str, dict[str, float]] = {}
        for sp in cfg.splits:
            for side_name in ("train", "val", "test"):
                for wsi, prop in getattr(sp, side_name).items():
                    if wsi == "cell_type_proportions":
                        continue
                    all_wsi_props[wsi] = max(all_wsi_props.get(wsi, 0.0), float(prop))
            for side in (sp.train, sp.val, sp.test):
                parsed = _parse_wsi_ct_props(side)
                if parsed:
                    all_ct_props.update(parsed)

        emb, cell_ids, cell_types, wsi_names = load_probe_population(
            all_wsi_props, base_path, embeddings_datasets, mapping, rng,
            wsi_cell_type_proportions=all_ct_props or None, consider_matching=consider_matching,
        )
        n = len(cell_ids)
        perm = rng.permutation(n)
        cut_train, cut_val = int(n * 0.7), int(n * 0.85)
        idx_train, idx_val, idx_test = perm[:cut_train], perm[cut_train:cut_val], perm[cut_val:]
        train_emb, val_emb, test_emb = emb[idx_train], emb[idx_val], emb[idx_test]
        train_ids, val_ids, test_ids = cell_ids[idx_train], cell_ids[idx_val], cell_ids[idx_test]
        train_types, val_types, test_types = cell_types[idx_train], cell_types[idx_val], cell_types[idx_test]
        train_wsi, val_wsi, test_wsi = wsi_names[idx_train], wsi_names[idx_val], wsi_names[idx_test]
        split_label = "same_wsi_split"
        split_info: dict[str, Any] = {
            "mode": "same_wsi_split", "all_wsis": {k: float(v) for k, v in all_wsi_props.items()},
            "consider_matching": consider_matching, "seed": seed,
        }
    else:
        sp = cfg.splits[split_idx]
        train_props, val_props, test_props = _wsi_props(sp.train), _wsi_props(sp.val), _wsi_props(sp.test)
        train_ct_props, val_ct_props, test_ct_props = (
            _parse_wsi_ct_props(sp.train), _parse_wsi_ct_props(sp.val), _parse_wsi_ct_props(sp.test)
        )

        train_emb, train_ids, train_types, train_wsi = load_probe_population(
            train_props, base_path, embeddings_datasets, mapping, rng,
            wsi_cell_type_proportions=train_ct_props, consider_matching=consider_matching,
        )
        val_emb, val_ids, val_types, val_wsi = load_probe_population(
            val_props, base_path, embeddings_datasets, mapping, rng,
            wsi_cell_type_proportions=val_ct_props, consider_matching=consider_matching,
        )
        test_emb, test_ids, test_types, test_wsi = load_probe_population(
            test_props, base_path, embeddings_datasets, mapping, rng,
            wsi_cell_type_proportions=test_ct_props, consider_matching=consider_matching,
        )
        split_label = f"split_{split_idx}"
        split_info = {
            "mode": "lwo", "split_idx": split_idx, "train": train_props, "val": val_props, "test": test_props,
            "consider_matching": consider_matching, "seed": seed,
        }

    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_dir / "split_informations.yaml", "w") as f:
        yaml.dump({
            **split_info,
            "train_size": int(len(train_ids)), "val_size": int(len(val_ids)), "test_size": int(len(test_ids)),
        }, f)
    print(f"[probing] {split_label}: train={len(train_ids)} cells, val={len(val_ids)} cells, "
          f"test={len(test_ids)} cells, embedding_dim={train_emb.shape[1] if train_emb.size else 0}")

    _, train_ctx = _build_context(train_emb, train_ids, train_types, train_wsi, boundary_cache, population_cache)
    _, val_ctx = _build_context(val_emb, val_ids, val_types, val_wsi, boundary_cache, population_cache)
    _, test_ctx = _build_context(test_emb, test_ids, test_types, test_wsi, boundary_cache, population_cache)

    probes = _build_active_probes(cfg)
    print(f"[probing] Running {len(probes)} probe(s): {[p.name for p in probes]}")

    mlflow.set_tracking_uri(cfg.mlflow.tracking_uri)
    mlflow.set_experiment(cfg.mlflow.experiment_name)
    run_name = f"{cfg.data.model_name}__{cfg.data.correction_name}__{split_label}"

    probe_summaries: dict[str, Any] = {}

    with mlflow.start_run(run_name=run_name):
        mlflow.log_params({
            "model_name": cfg.data.model_name, "correction_name": cfg.data.correction_name,
            "split_label": split_label, "mapping": cfg.mapping, "seed": seed,
            "train_size": int(len(train_ids)), "val_size": int(len(val_ids)), "test_size": int(len(test_ids)),
            "probes": [p.name for p in probes],
        })

        for probe in probes:
            lambdas = _lambdas_for(probe, cfg)
            result = run_probe(
                probe, train_ctx, val_ctx, test_ctx, train_emb, val_emb, test_emb, lambdas, device,
            )
            probe_dir = output_dir / _safe_dirname(probe.name)
            probe_dir.mkdir(parents=True, exist_ok=True)

            with mlflow.start_run(run_name=probe.name, nested=True):
                mlflow.log_params({
                    "probe": probe.name, "task_type": probe.task_type, "lambdas": lambdas,
                    "n_train": result.n_train, "n_val": result.n_val, "n_test": result.n_test,
                    "skipped": result.skipped,
                })
                if result.skipped:
                    print(f"[probing] probe '{probe.name}' skipped: {result.skip_reason}")
                    probe_summaries[probe.name] = {"skipped": True, "reason": result.skip_reason}
                    continue

                mlflow.log_table(pd.DataFrame(result.trial_rows), artifact_file="lambda_sweep.json")
                best_row = next(r for r in result.trial_rows if r["lambda"] == result.best_lambda)
                mlflow.log_metrics({
                    k: v for k, v in best_row.items()
                    if k != "lambda" and isinstance(v, (int, float)) and np.isfinite(v)
                })
                mlflow.log_param("best_lambda", result.best_lambda)

                pd.DataFrame(result.trial_rows).to_csv(probe_dir / "lambda_sweep_results.csv", index=False)

                summary = {
                    "probe": probe.name, "task_type": probe.task_type, "target_columns": result.target_columns,
                    "best_lambda": result.best_lambda, "n_train": result.n_train, "n_val": result.n_val,
                    "n_test": result.n_test, "best_val_metrics": result.val_fit.metrics,
                    "best_test_metrics": result.test_fit.metrics if result.test_fit else None,
                }
                with open(probe_dir / "results_summary.yaml", "w") as f:
                    yaml.dump(summary, f, default_flow_style=False)
                probe_summaries[probe.name] = {
                    "skipped": False, "best_lambda": result.best_lambda,
                    "val_selection_metric": result.val_fit.metrics.get("selection_metric"),
                    "test_selection_metric": (result.test_fit.metrics.get("selection_metric")
                                               if result.test_fit else None),
                }

                # ── per-cell results, for further analysis ──────────────────────────
                rows = []
                for split_name, fit in (("val", result.val_fit), ("test", result.test_fit)):
                    if fit is None:
                        continue
                    reported = probe.predictions_to_report(fit.y_true, fit.y_pred)
                    df = pd.DataFrame({
                        "cell_id": fit.cell_ids, "wsi": fit.wsi_names,
                        "split": split_name, **reported,
                    })
                    rows.append(df)
                if rows:
                    pd.concat(rows, ignore_index=True).to_csv(probe_dir / "per_cell_results.csv", index=False)

                print(f"[probing] probe '{probe.name}': best_lambda={result.best_lambda} "
                      f"val_selection_metric={result.val_fit.metrics['selection_metric']:.4f}")

    with open(output_dir / "probes_summary.yaml", "w") as f:
        yaml.dump(probe_summaries, f, default_flow_style=False)
    print(f"[probing] Done. {split_label} probe summary: {probe_summaries}")


# ── Hydra entry point ─────────────────────────────────────────────────────────

@hydra.main(config_path="../../../configs", config_name="probing_colon", version_base="1.3")
def main(cfg: DictConfig) -> None:
    import torch

    split_idx: Optional[int] = OmegaConf.select(cfg, "split_idx")
    if split_idx is None:
        print("ERROR: split_idx is required. Pass split_idx=<N> (or split_idx=-1 for same_wsi_split).",
              file=sys.stderr)
        sys.exit(1)

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"[probing] device={device}, split_idx={split_idx}")

    repo_root = Path(hydra.utils.get_original_cwd())
    outputs_folder_name: str = str(OmegaConf.select(cfg, "output_dir", default="outputs_probing"))
    output_base = repo_root / outputs_folder_name / cfg.data.model_name / cfg.data.correction_name
    split_label = "same_wsi_split" if split_idx == -1 else f"split_{split_idx}"
    consider_matching: bool = bool(OmegaConf.select(cfg, "data.consider_matching", default=True))
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    output_dir = (
        output_base / cfg.mapping / _matching_folder_name(consider_matching)
        / _embeddings_folder_name(embeddings_datasets) / split_label
    )

    run_split_experiment(split_idx, cfg, device, output_dir)


if __name__ == "__main__":
    main()
