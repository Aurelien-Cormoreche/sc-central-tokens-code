"""
Layer 2 — Experiment runner for one train/test split.

Loads data once, runs a full grid search over all active hyperparameters,
logs each trial to MLflow, and writes results to outputs/.

Invoked by the SLURM jobs generated by launcher.py:
    python -m src.python.classifier_training.experiment \
        split_idx=0 data.model_name=virchow_v2 data.correction_name=scanorama
"""
import itertools
import os
import sys
from pathlib import Path
from typing import Any, Optional

import mlflow
import numpy as np
import pandas as pd
import torch
import yaml
from omegaconf import DictConfig, OmegaConf

import hydra

from src.python.classifier_training.trainer import TrainConfig, train_and_evaluate
from src.python.code_configs.mappings import mapping_factory
from src.python.utils.loading_functions import load_data


# ── helpers ──────────────────────────────────────────────────────────────────

def _build_label_encoder(mapping: dict) -> tuple[list[str], dict[str, int]]:
    """Return (sorted class names, label-to-int dict) from a cell-type mapping.

    "Unknown" cells (couldn't be confidently typed) are excluded entirely -- they
    are not a real cell-type class, so they get no output neuron and are dropped
    from every split at load time (see _load_wsi_data).
    """
    class_names = sorted(set(mapping.values()) - {"Unknown"})
    label_enc = {name: i for i, name in enumerate(class_names)}
    return class_names, label_enc


def _load_wsi_data(
    wsi_proportions: dict[str, float],
    base_path: str,
    embeddings_datasets: list[str],
    mapping: dict,
    label_enc: dict[str, int],
    rng: np.random.Generator,
    wsi_cell_type_proportions: Optional[dict[str, dict[str, float]]] = None,
    consider_matching: bool = True,
) -> tuple[np.ndarray, torch.Tensor, torch.Tensor]:
    """Load cells from a set of WSIs, subsample by WSI proportion then per-WSI cell-type proportions, encode labels."""
    wsi_names = list(wsi_proportions.keys())

    embeddings, cell_labels, _, wsi_origin, _, wsi_idx_map = load_data(
        base_path, embeddings_datasets, wsi_names, mapping, consider_matching=consider_matching
    )

    # Drop "Unknown" cells before any proportion sampling, so e.g. proportion=1.0
    # keeps 100% of the WSI's typed cells rather than 100% of everything.
    known_mask = cell_labels != "Unknown"
    embeddings = embeddings[known_mask]
    cell_labels = cell_labels[known_mask]
    wsi_origin = wsi_origin[known_mask]

    keep_indices: list[np.ndarray] = []
    for wsi_idx, wsi_name in enumerate(wsi_idx_map):
        proportion = float(wsi_proportions[wsi_name])
        wsi_mask = np.where(wsi_origin == wsi_idx)[0]
        if len(wsi_mask) == 0:
            raise ValueError(
                f"WSI '{wsi_name}' contributed 0 usable cells (either its "
                f"embeddings_dataset.h5 has no cells, or every cell's label "
                f"mapped to 'Unknown' and was dropped) -- base_path={base_path!r}"
            )
        n_keep = max(1, int(len(wsi_mask) * proportion))
        selected = rng.choice(wsi_mask, size=n_keep, replace=False)

        ct_props = wsi_cell_type_proportions.get(wsi_name) if wsi_cell_type_proportions else None
        if ct_props:
            wsi_labels = cell_labels[selected]
            ct_keep: list[np.ndarray] = []
            for ct in np.unique(wsi_labels):
                ct_mask = np.where(wsi_labels == ct)[0]
                ct_prop = float(ct_props.get(ct, 1.0))
                # ct_prop == 0.0 means "exclude this cell type entirely" -- no min-1 floor.
                # For any ct_prop > 0, keep the min-1 floor so a requested-but-tiny fraction
                # doesn't round down to zero.
                n_keep_ct = 0 if ct_prop <= 0 else max(1, int(len(ct_mask) * ct_prop))
                if n_keep_ct > 0:
                    ct_keep.append(selected[rng.choice(ct_mask, size=min(n_keep_ct, len(ct_mask)), replace=False)])
            # Empty ct_keep can mean either "ct_props was empty to begin with" (selected was
            # already empty) or "every present cell type resolved to 0 kept" -- both cases
            # should yield an empty selection, not silently fall back to the pre-downsampling
            # `selected` (which would defeat an explicit ct_prop=0.0 request).
            selected = np.sort(np.concatenate(ct_keep)) if ct_keep else selected[:0]

        keep_indices.append(selected)

    keep = np.concatenate(keep_indices)
    emb = embeddings[keep]
    labels_str = cell_labels[keep]
    wsi_orig = wsi_origin[keep]

    labels_int = torch.tensor(
        [label_enc[lbl] for lbl in labels_str],
        dtype=torch.long,
    )
    wsi_orig_t = torch.tensor(wsi_orig, dtype=torch.long)
    return emb, labels_int, wsi_orig_t


def _build_grid(hparams_cfg: DictConfig) -> list[dict[str, Any]]:
    """Expand the hparams config into a flat list of all hyperparameter combinations."""
    param_lists: dict[str, list] = {}
    for name, spec in hparams_cfg.items():
        if spec["tune"]:
            param_lists[name] = list(OmegaConf.to_container(spec["values"], resolve=True))
        else:
            values = OmegaConf.to_container(spec["values"], resolve=True)
            param_lists[name] = [values[0] if isinstance(values, list) else values]
    keys = list(param_lists.keys())
    combos = list(itertools.product(*[param_lists[k] for k in keys]))
    return [dict(zip(keys, combo)) for combo in combos]


def _class_counts(labels: torch.Tensor, num_classes: int, class_names: list[str]) -> dict[str, int]:
    counts = torch.bincount(labels, minlength=num_classes)
    return {class_names[i]: int(counts[i]) for i in range(num_classes)}


def _restrict_to_train_classes(
    train_labels: torch.Tensor,
    eval_sets: dict[str, tuple[np.ndarray, torch.Tensor, torch.Tensor]],
    class_names: list[str],
) -> tuple[torch.Tensor, dict[str, tuple[np.ndarray, torch.Tensor, torch.Tensor, int]], list[str]]:
    """Restrict the model's label space to classes actually present in train_labels.

    Remaps train and every eval set's labels onto a compact 0..k-1 encoding over just those
    classes, and drops any eval cell whose true class has zero train support -- the model has
    no output neuron for it and can never predict it correctly, so it's excluded from evaluation
    rather than silently scored as a permanent miss.

    Args:
        eval_sets: name -> (embeddings, labels, wsi_origins), e.g. {"val": ..., "test": ...}

    Returns:
        (new_train_labels, {name: (emb, labels, wsi_origins, n_dropped)}, new_class_names)
    """
    present = sorted(int(c) for c in torch.unique(train_labels).tolist())
    new_class_names = [class_names[i] for i in present]
    remap = {old: new for new, old in enumerate(present)}

    new_train_labels = torch.tensor(
        [remap[int(l)] for l in train_labels.tolist()], dtype=torch.long
    )

    new_eval_sets: dict[str, tuple[np.ndarray, torch.Tensor, torch.Tensor, int]] = {}
    for name, (emb, labels, wsi) in eval_sets.items():
        labels_list = [int(l) for l in labels.tolist()]
        keep_mask = np.array([l in remap for l in labels_list])
        n_dropped = int((~keep_mask).sum())

        new_emb = emb[keep_mask]
        new_wsi = wsi[keep_mask]
        new_labels = torch.tensor(
            [remap[l] for l in np.asarray(labels_list)[keep_mask]], dtype=torch.long
        )
        new_eval_sets[name] = (new_emb, new_labels, new_wsi, n_dropped)

    return new_train_labels, new_eval_sets, new_class_names


def _matching_folder_name(consider_matching: bool) -> str:
    return "matching" if consider_matching else "all_cells"


def _embeddings_folder_name(embeddings_datasets: list[str]) -> str:
    return "_".join(sorted(embeddings_datasets)) if embeddings_datasets else "default"


# ── main experiment logic ─────────────────────────────────────────────────────

def run_split_experiment(
    split_idx: int,
    cfg: DictConfig,
    device: str,
    output_dir: Path,
) -> None:
    mapping = mapping_factory(cfg.mapping)
    class_names, label_enc = _build_label_encoder(mapping)
    num_classes = len(class_names)

    base_path = os.path.join(
        cfg.data.base_dir, f'{cfg.data.model_name}_h5', cfg.data.correction_name
    )
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    consider_matching: bool = bool(OmegaConf.select(cfg, "data.consider_matching", default=True))
    seed = int(OmegaConf.select(cfg, "seed", default=42))
    rng = np.random.default_rng(seed)

    def _parse_wsi_ct_props(sp_side) -> Optional[dict[str, dict[str, float]]]:
        raw = OmegaConf.select(sp_side, "cell_type_proportions")
        if not raw:
            return None
        return {wsi: {ct: float(p) for ct, p in ct_map.items()} for wsi, ct_map in raw.items()}

    # ── data loading ──────────────────────────────────────────────────────────
    if split_idx == -1:
        # same_wsi_split: pool all WSIs across every split, random 70/15/15
        all_wsi_props: dict[str, float] = {}
        all_ct_props: dict[str, dict[str, float]] = {}
        for sp in cfg.splits:
            for side_name in ("train", "val", "test"):
                for wsi, prop in getattr(sp, side_name).items():
                    if wsi == "cell_type_proportions":
                        continue
                    all_wsi_props[wsi] = max(all_wsi_props.get(wsi, 0.0), float(prop))
            for side in (sp.train, sp.val, sp.test):
                parsed = _parse_wsi_ct_props(side)
                if parsed:
                    all_ct_props.update(parsed)

        emb, labels, wsi_orig = _load_wsi_data(
            all_wsi_props, base_path, embeddings_datasets, mapping, label_enc, rng,
            wsi_cell_type_proportions=all_ct_props or None,
            consider_matching=consider_matching,
        )
        n = len(labels)
        perm = rng.permutation(n)
        cut_train = int(n * 0.7)
        cut_val = int(n * 0.85)
        train_emb = emb[perm[:cut_train]]
        train_labels = labels[perm[:cut_train]]
        train_wsi = wsi_orig[perm[:cut_train]]
        val_emb = emb[perm[cut_train:cut_val]]
        val_labels = labels[perm[cut_train:cut_val]]
        val_wsi = wsi_orig[perm[cut_train:cut_val]]
        test_emb = emb[perm[cut_val:]]
        test_labels = labels[perm[cut_val:]]
        test_wsi = wsi_orig[perm[cut_val:]]
        split_label = "same_wsi_split"
        split_info: dict[str, Any] = {
            "mode": "same_wsi_split",
            "all_wsis": {k: float(v) for k, v in all_wsi_props.items()},
            "cell_type_proportions": all_ct_props or None,
            "consider_matching": consider_matching,
            "seed": seed,
        }
    else:
        sp = cfg.splits[split_idx]
        train_props = {k: float(v) for k, v in sp.train.items() if k != "cell_type_proportions"}
        test_props = {k: float(v) for k, v in sp.test.items() if k != "cell_type_proportions"}
        train_ct_props = _parse_wsi_ct_props(sp.train)
        test_ct_props = _parse_wsi_ct_props(sp.test)

        train_emb, train_labels, train_wsi = _load_wsi_data(
            train_props, base_path, embeddings_datasets, mapping, label_enc, rng,
            wsi_cell_type_proportions=train_ct_props,
            consider_matching=consider_matching,
        )

        test_emb, test_labels, test_wsi = _load_wsi_data(
            test_props, base_path, embeddings_datasets, mapping, label_enc, rng,
            wsi_cell_type_proportions=test_ct_props,
            consider_matching=consider_matching,
        )

        # Splits with no `val` key (e.g. configs/unbalanced/train_unbalanced_alpha_*.yaml,
        # which predate the train/val/test refactor and can't cheaply grow a val slide --
        # see generate_unbalanced_configs.py) fall back to reusing test as val. That
        # reintroduces test-set leakage into hyperparameter selection for those configs
        # specifically; every split in configs/train.yaml defines a real val and is unaffected.
        has_val = OmegaConf.select(sp, "val") is not None
        if has_val:
            val_props = {k: float(v) for k, v in sp.val.items() if k != "cell_type_proportions"}
            val_ct_props = _parse_wsi_ct_props(sp.val)
            val_emb, val_labels, val_wsi = _load_wsi_data(
                val_props, base_path, embeddings_datasets, mapping, label_enc, rng,
                wsi_cell_type_proportions=val_ct_props,
                consider_matching=consider_matching,
            )
        else:
            val_props, val_ct_props = test_props, test_ct_props
            val_emb, val_labels, val_wsi = test_emb, test_labels, test_wsi

        split_label = f"split_{split_idx}"
        split_info = {
            "mode": "lwo",
            "split_idx": split_idx,
            "train": train_props,
            "val": val_props,
            "test": test_props,
            "train_cell_type_proportions": train_ct_props,
            "val_cell_type_proportions": val_ct_props,
            "test_cell_type_proportions": test_ct_props,
            "val_reused_test": not has_val,
            "consider_matching": consider_matching,
            "seed": seed,
        }

    # ── save split metadata (full label space, before restricting to classes
    # present in train) ───────────────────────────────────────────────────────
    output_dir.mkdir(parents=True, exist_ok=True)
    full_train_class_counts = _class_counts(train_labels, num_classes, class_names)
    full_val_class_counts = _class_counts(val_labels, num_classes, class_names)
    full_test_class_counts = _class_counts(test_labels, num_classes, class_names)

    # ── restrict the model's class space to what's actually present in train;
    # val/test cells of classes with zero train support are dropped (see docstring) ──
    train_labels, restricted, class_names = _restrict_to_train_classes(
        train_labels,
        {"val": (val_emb, val_labels, val_wsi), "test": (test_emb, test_labels, test_wsi)},
        class_names,
    )
    val_emb, val_labels, val_wsi, n_val_dropped = restricted["val"]
    test_emb, test_labels, test_wsi, n_test_dropped = restricted["test"]
    num_classes = len(class_names)

    with open(output_dir / "split_informations.yaml", "w") as f:
        yaml.dump(
            {
                **split_info,
                "train_size": int(len(train_labels)),
                "val_size": int(len(val_labels)),
                "test_size": int(len(test_labels)),
                "val_cells_dropped_absent_from_train": n_val_dropped,
                "test_cells_dropped_absent_from_train": n_test_dropped,
                "class_names": class_names,
                "train_class_counts": full_train_class_counts,
                "val_class_counts": full_val_class_counts,
                "test_class_counts": full_test_class_counts,
            },
            f,
        )
    print(
        f"[experiment] {split_label}: "
        f"train={len(train_labels)} cells, val={len(val_labels)} cells, test={len(test_labels)} cells "
        f"({n_val_dropped} val / {n_test_dropped} test cells dropped, absent from train), "
        f"classes={class_names}, embedding_dim={train_emb.shape[1]}"
    )

    # ── grid search ───────────────────────────────────────────────────────────
    input_dim: int = train_emb.shape[1]
    grid = _build_grid(cfg.hparams)
    print(f"[experiment] Running {len(grid)} trials on {device}")

    mlflow.set_tracking_uri(cfg.mlflow.tracking_uri)
    mlflow.set_experiment(cfg.mlflow.experiment_name)
    run_name = f"{cfg.data.model_name}__{cfg.data.correction_name}__{split_label}"

    trial_rows: list[dict] = []
    best_trial: Optional[dict] = None

    with mlflow.start_run(run_name=run_name):
        mlflow.log_params(
            {
                "model_name": cfg.data.model_name,
                "correction_name": cfg.data.correction_name,
                "split_label": split_label,
                "mapping": cfg.mapping,
                "num_trials": len(grid),
                "seed": seed,
                "train_size": int(len(train_labels)),
                "val_size": int(len(val_labels)),
                "test_size": int(len(test_labels)),
            }
        )

        for trial_idx, hparams in enumerate(grid):
            pca_val: Optional[int] = (
                int(hparams["pca_components"]) if hparams["pca_components"] is not None else None
            )
            train_cfg = TrainConfig(
                input_dim=input_dim,
                num_classes=num_classes,
                class_names=class_names,
                learning_rate=float(hparams["learning_rate"]),
                dropout=float(hparams["dropout"]),
                hidden_dim=int(hparams["hidden_dim"]),
                pca_components=pca_val,
                normalization=str(hparams["normalization"]),
                loss_weights=str(hparams["loss_weights"]),
                num_epochs=int(cfg.training.num_epochs),
                batch_size=int(cfg.training.batch_size),
                seed=seed,
            )

            with mlflow.start_run(run_name=f"trial_{trial_idx}", nested=True):
                mlflow.log_params(
                    {k: (str(v) if v is None else v) for k, v in hparams.items()}
                )

                metrics = train_and_evaluate(
                    train_emb, train_labels, train_wsi,
                    test_emb, test_labels, test_wsi,
                    train_cfg, device,
                    val_embeddings=val_emb, val_labels=val_labels, val_wsi_origins=val_wsi,
                )
                flat_metrics = {
                    k: v for k, v in metrics.items()
                    if k not in ("val_per_class_f1", "val_confusion_matrix",
                                 "test_per_class_f1", "test_confusion_matrix",
                                 "train_loss_curve", "val_loss_curve")
                }
                mlflow.log_metrics(flat_metrics)
                for epoch, (trl, vll) in enumerate(
                    zip(metrics["train_loss_curve"], metrics["val_loss_curve"])
                ):
                    mlflow.log_metrics(
                        {"train_loss": trl, "val_loss": vll}, step=epoch
                    )
                for class_name, f1_class in metrics['val_per_class_f1'].items():
                    mlflow.log_metric(f'f1_val_{class_name}', f1_class)
                for class_name, f1_class in metrics['test_per_class_f1'].items():
                    mlflow.log_metric(f'f1_test_{class_name}', f1_class)

                val_cm_df = pd.DataFrame(metrics['val_confusion_matrix'], index=class_names, columns=class_names)
                mlflow.log_table(val_cm_df, artifact_file="confusion_matrix_val.json")
                test_cm_df = pd.DataFrame(metrics['test_confusion_matrix'], index=class_names, columns=class_names)
                mlflow.log_table(test_cm_df, artifact_file="confusion_matrix_test.json")


            row: dict[str, Any] = {"trial_idx": trial_idx, **hparams, **flat_metrics}
            trial_rows.append(row)

            if best_trial is None or flat_metrics["val_macro_f1"] > best_trial["val_macro_f1"]:
                best_trial = {
                    **row,
                    "val_per_class_f1": metrics["val_per_class_f1"],
                    "test_per_class_f1": metrics["test_per_class_f1"],
                    "val_confusion_matrix": metrics["val_confusion_matrix"],
                    "test_confusion_matrix": metrics["test_confusion_matrix"],
                    "train_loss_curve": metrics["train_loss_curve"],
                    "val_loss_curve": metrics["val_loss_curve"],
                }


            print(
                f"[experiment] Trial {trial_idx + 1}/{len(grid)} — "
                f"val_macro_f1={flat_metrics['val_macro_f1']:.4f} "
                f"test_macro_f1={flat_metrics['test_macro_f1']:.4f}"
            )

    # ── save results ─────────────────────────────────────────────────────────
    pd.DataFrame(trial_rows).to_csv(output_dir / "grid_search_results.csv", index=False)

    assert best_trial is not None
    np.save(output_dir / "best_train_loss_curve.npy", np.array(best_trial["train_loss_curve"]))
    np.save(output_dir / "best_val_loss_curve.npy", np.array(best_trial["val_loss_curve"]))

    metric_keys = ("accuracy", "macro_f1", "weighted_f1", "balanced_accuracy", "loss")
    summary = {
        "best_config": {
            k: best_trial[k]
            for k in ("learning_rate", "dropout", "hidden_dim", "pca_components",
                       "normalization", "loss_weights")
        },
        "best_val_metrics": {k: best_trial[f"val_{k}"] for k in metric_keys},
        "best_test_metrics": {k: best_trial[f"test_{k}"] for k in metric_keys},
        "val_per_class_f1": best_trial["val_per_class_f1"],
        "test_per_class_f1": best_trial["test_per_class_f1"],
        "all_trial_results": trial_rows,
    }
    with open(output_dir / "results_summary.yaml", "w") as f:
        yaml.dump(summary, f, default_flow_style=False)

    print(
        f"[experiment] Done. Best (selected on val) val_macro_f1={best_trial['val_macro_f1']:.4f}, "
        f"test_macro_f1={best_trial['test_macro_f1']:.4f} with config {summary['best_config']}"
    )


# ── Hydra entry point ─────────────────────────────────────────────────────────

@hydra.main(config_path="../../../configs", config_name="train", version_base="1.3")
def main(cfg: DictConfig) -> None:
    split_idx: Optional[int] = OmegaConf.select(cfg, "split_idx")
    if split_idx is None:
        print(
            "ERROR: split_idx is required. "
            "Pass split_idx=<N> (or split_idx=-1 for same_wsi_split).",
            file=sys.stderr,
        )
        sys.exit(1)

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"[experiment] device={device}, split_idx={split_idx}")

    repo_root = Path(hydra.utils.get_original_cwd())
    outputs_folder_name: str = str(OmegaConf.select(cfg, "output_dir", default="outputs"))
    output_base = repo_root / outputs_folder_name / cfg.data.model_name / cfg.data.correction_name
    split_label = "same_wsi_split" if split_idx == -1 else f"split_{split_idx}"
    consider_matching: bool = bool(OmegaConf.select(cfg, "data.consider_matching", default=True))
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    output_dir = (
        output_base / cfg.mapping
        / _matching_folder_name(consider_matching)
        / _embeddings_folder_name(embeddings_datasets)
        / split_label
    )

    run_split_experiment(split_idx, cfg, device, output_dir)


if __name__ == "__main__":
    main()
