from src.python.deepspot_training.data.custom_dataloader import CustomDeepCellDataLoader, load_hvg_table
from src.python.deepspot_training.trainer import TrainConfig, train_and_evaluate


# ── helpers ────────────────────────────────────────────────────────────────────

def _build_grid(hparams_cfg: DictConfig) -> list[dict[str, Any]]:
    """Expand the hparams config into a flat list of all hyperparameter combinations.
    Same pattern as classifier_training/experiment.py::_build_grid."""
    param_lists: dict[str, list] = {}
    for name, spec in hparams_cfg.items():
        if spec["tune"]:
            param_lists[name] = list(OmegaConf.to_container(spec["values"], resolve=True))
        else:
            values = OmegaConf.to_container(spec["values"], resolve=True)
            param_lists[name] = [values[0] if isinstance(values, list) else values]
    keys = list(param_lists.keys())
    combos = list(itertools.product(*[param_lists[k] for k in keys]))
    return [dict(zip(keys, combo)) for combo in combos]


def _matching_folder_name(consider_matching: bool) -> str:
    return "matching" if consider_matching else "all_cells"


def _embeddings_folder_name(embeddings_datasets: list[str]) -> str:
    return "_".join(sorted(embeddings_datasets)) if embeddings_datasets else "default"


def _resolve_split(cfg: DictConfig, split_idx: int) -> tuple[list[str], Optional[list[str]], dict]:
    """
    Resolve the train/val WSI lists for this split.

    split_idx == -1 (same_wsi_split, upper bound): pool every WSI across all configured splits into
    one set; train_wsis == val_wsis == that pooled set, and the train/val cell split happens at the
    *cell* level (see run_split_experiment) rather than by WSI, matching the classifier's same-WSI
    upper-bound mode. NOTE: this means the highly-variable-gene selection also sees val cells — an
    optimistic upper bound, same caveat as the classifier's same_wsi_split.

    split_idx >= 0 (LWO): train/val WSIs come from cfg.splits[split_idx].train / .test.
    `cell_type_proportions` sub-keys (classifier-specific) are ignored if present.
    """
    if split_idx == -1:
        all_wsis: set[str] = set()
        for sp in cfg.splits:
            all_wsis.update(k for k in sp.train.keys() if k != "cell_type_proportions")
            all_wsis.update(k for k in sp.test.keys() if k != "cell_type_proportions")
        wsis = sorted(all_wsis)
        info = {"mode": "same_wsi_split", "wsis": wsis}
        return wsis, None, info

    sp = cfg.splits[split_idx]
    train_wsis = [k for k in sp.train.keys() if k != "cell_type_proportions"]
    val_wsis = [k for k in sp.test.keys() if k != "cell_type_proportions"]
    info = {"mode": "lwo", "split_idx": split_idx, "train_wsis": train_wsis, "val_wsis": val_wsis}
    return train_wsis, val_wsis, info


def _load_precomputed_hvgs(cfg: DictConfig, split_idx: int, num_genes: int) -> Optional[pd.DataFrame]:
    """
    Load the split's precomputed HVG ranking (see compute_hvgs.py / scripts/compute_hvgs.sh), if
    `data.hvg_dir` is set. Returns None (on-the-fly fallback in load_data) if unset.
    """
    hvg_dir = OmegaConf.select(cfg, "data.hvg_dir", default=None)
    if not hvg_dir:
        return None

    split_label = "same_wsi_split" if split_idx == -1 else f"split_{split_idx}"
    path = Path(hvg_dir)
    if not path.is_absolute():
        path = Path(hydra.utils.get_original_cwd()) / path
    path = path / f"{split_label}.csv"

    if not path.exists():
        raise FileNotFoundError(
            f"No precomputed HVG file at {path}. Run `sbatch scripts/compute_hvgs.sh` (or "
            "`python -m src.python.deepspot_training.compute_hvgs`) first, or set data.hvg_dir=null "
            "to compute HVGs on the fly instead (only advisable on a large-memory node)."
        )
    return load_hvg_table(str(path), num_genes)


def _build_dataset(cfg: DictConfig, wsis: list[str], num_genes=None, highly_variable_genes=None):
    embeddings_dir = os.path.join(cfg.data.base_dir, f"{cfg.data.model_name}_h5", cfg.data.correction_name)
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    return CustomDeepCellDataLoader(
        adata_path=cfg.data.adata_path_template,
        embeddings_dir=embeddings_dir,
        embeddings_datasets=embeddings_datasets,
        samples=wsis,
        num_genes=num_genes,
        target_sum=float(cfg.data.target_sum),
        raw_counts=bool(cfg.data.raw_counts),
        resolution=int(cfg.data.resolution),
        cell_context=str(cfg.data.cell_context),
        n_neighbors=int(cfg.data.n_neighbors),
        consider_matching=bool(OmegaConf.select(cfg, "data.consider_matching", default=True)),
        highly_variable_genes=highly_variable_genes,
    )


def _gene_interval_stats(genes_table: pd.DataFrame, per_gene_pearson: dict, gene_interval: list[int]) -> pd.DataFrame:
    """
    Post-hoc reporting aggregation: for each `n` in `gene_interval`, restrict to the `n` most
    highly-variable genes *within the trained set* (by `highly_variable_rank`, ascending — 0 = most
    variable) and report mean/median Pearson over just that subset. No retraining, no further HVG
    computation — the model is trained once, on the full `num_genes` trained set.
    """
    hv = genes_table[genes_table["highly_variable"]].copy()
    hv["pearson"] = hv["gene_name"].map(per_gene_pearson)
    hv = hv.sort_values("highly_variable_rank")

    rows = []
    for n in gene_interval:
        subset = hv.iloc[: min(int(n), len(hv))]
        vals = subset["pearson"].dropna().to_numpy()
        rows.append({
            "num_genes": int(n),
            "n_genes_used": int(len(subset)),
            "mean_pearson": float(np.mean(vals)) if len(vals) else float("nan"),
            "median_pearson": float(np.median(vals)) if len(vals) else float("nan"),
        })
    return pd.DataFrame(rows)


def _plot_gene_interval_stats(stats: pd.DataFrame, out_path: Path) -> None:
    plt.figure(figsize=(5, 4))
    plt.plot(stats["num_genes"], stats["mean_pearson"], marker="o", label="mean")
    plt.plot(stats["num_genes"], stats["median_pearson"], marker="o", label="median")
    plt.xlabel("Top-N most variable genes (of the trained set)")
    plt.ylabel("Pearson correlation")
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


class _CellSubset:
    """Lightweight positional-index wrapper around a CustomDeepCellDataLoader, used for the
    same_wsi_split (cell-level 80/20, WSI-of-origin-agnostic) mode. Delegates __getitem__ to the
    base dataset and exposes `.scaler`/`.transcriptomics_df` live from the base dataset, so calling
    `base.set_normalization(...)` is immediately reflected in every subset without rebuilding it."""

    def __init__(self, base: CustomDeepCellDataLoader, indices: np.ndarray):
        self.base = base
        self.indices = np.asarray(indices)

    def __len__(self) -> int:
        return len(self.indices)

    def __getitem__(self, idx: int):
        return self.base[self.indices[idx]]

    @property
    def scaler(self):
        return self.base.scaler

    @property
    def transcriptomics_df(self):
        return self.base.transcriptomics_df.iloc[self.indices]


def _plot_pearson_distribution(per_gene_pearson: dict, out_path: Path) -> None:
    values = [v for v in per_gene_pearson.values() if not np.isnan(v)]
    plt.figure(figsize=(5, 4))
    plt.hist(values, bins=30)
    plt.xlabel("Pearson correlation")
    plt.ylabel("Number of genes")
    plt.title("Per-gene Pearson correlation (validation)")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


def _plot_training_curve(train_curve: list[float], val_curve: list[float], out_path: Path) -> None:
    plt.figure(figsize=(5, 4))
    plt.plot(train_curve, label="train")
    if val_curve:
        val_x = np.linspace(0, len(train_curve), num=len(val_curve))
        plt.plot(val_x, val_curve, label="val")
    plt.xlabel("Step")
    plt.ylabel("Loss")
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


# ── main experiment logic ─────────────────────────────────────────────────────

def run_split_experiment(split_idx: int, cfg: DictConfig, device: str, output_dir: Path) -> None:
    train_wsis, val_wsis, split_info = _resolve_split(cfg, split_idx)
    num_genes = int(cfg.data.num_genes)
    precomputed_genes = _load_precomputed_hvgs(cfg, split_idx, num_genes)

    print(f"[experiment] Loading data for split={split_idx} (num_genes={num_genes}, "
          f"n_neighbors={cfg.data.n_neighbors}, "
          f"hvg_source={'precomputed' if precomputed_genes is not None else 'on-the-fly'})")

    if split_idx == -1:
        full_dataset = _build_dataset(
            cfg, train_wsis, num_genes=num_genes, highly_variable_genes=precomputed_genes,
        )
        n = len(full_dataset)
        rng = np.random.default_rng(42)
        perm = rng.permutation(n)
        cut = int(n * 0.8)
        train_dataset = _CellSubset(full_dataset, perm[:cut])
        val_dataset = _CellSubset(full_dataset, perm[cut:])
        gene_names = full_dataset.gene_names
        genes_table = full_dataset.genes_table
        train_size, val_size = len(train_dataset), len(val_dataset)
        _base_for_normalization = full_dataset
    else:
        train_dataset = _build_dataset(
            cfg, train_wsis, num_genes=num_genes, highly_variable_genes=precomputed_genes,
        )
        val_dataset = _build_dataset(
            cfg, val_wsis, highly_variable_genes=train_dataset.genes_table,
        )
        gene_names = train_dataset.gene_names
        genes_table = train_dataset.genes_table
        train_size, val_size = len(train_dataset), len(val_dataset)
        _base_for_normalization = None

    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_dir / "split_informations.yaml", "w") as f:
        yaml.dump({
            **split_info,
            "num_genes": num_genes,
            "n_neighbors": int(cfg.data.n_neighbors),
            "train_size": int(train_size),
            "val_size": int(val_size),
        }, f)

    pd.Series(gene_names, name="gene_name").to_csv(output_dir / "genes_used.csv", index=False)

    print(f"[experiment] split={split_idx}: train={train_size} cells, val={val_size} cells, "
          f"n_genes={len(gene_names)}")

    # ── grid search over model/training hyperparameters ─────────────────────────
    input_dim = (
        train_dataset[0][0][0].shape[-1]
        if isinstance(train_dataset[0][0], tuple)
        else train_dataset[0][0].shape[-1]
    )
    grid = _build_grid(cfg.hparams)
    print(f"[experiment] Running {len(grid)} trials on {device}")

    mlflow.set_tracking_uri(cfg.mlflow.tracking_uri)
    mlflow.set_experiment(cfg.mlflow.experiment_name)
    split_label = "same_wsi_split" if split_idx == -1 else f"split_{split_idx}"
    run_name = f"{cfg.data.model_name}__{cfg.data.correction_name}__{split_label}__deepcell"

    trial_rows: list[dict] = []
    best_trial: Optional[dict] = None

    with mlflow.start_run(run_name=run_name):
        mlflow.log_params({
            "model_name": cfg.data.model_name,
            "correction_name": cfg.data.correction_name,
            "split_label": split_label,
            "num_genes": num_genes,
            "n_neighbors": int(cfg.data.n_neighbors),
            "num_trials": len(grid),
            "train_size": int(train_size),
            "val_size": int(val_size),
        })

        for trial_idx, hparams in enumerate(grid):
            if split_idx == -1:
                # One shared base dataset; _CellSubset.scaler/.transcriptomics_df read from it live.
                _base_for_normalization.set_normalization(hparams["gene_normalization"])
            else:
                scaler = train_dataset.set_normalization(hparams["gene_normalization"])
                val_dataset.set_normalization(hparams["gene_normalization"], scaler=scaler)

            train_cfg = TrainConfig(
                input_size=int(input_dim),
                output_size=len(gene_names),
                loss_func=str(hparams["loss_func"]),
                lr=float(hparams["learning_rate"]),
                p=float(hparams["dropout"]),
                weight_decay=float(hparams["weight_decay"]),
                n_ensemble=int(hparams["n_ensemble"]),
                phi2rho_size=int(hparams["phi2rho_size"]),
                emb_size=int(hparams["emb_size"]),
                agg_neighbors=str(hparams["agg_neighbors"]),
                cell_context=str(cfg.data.cell_context),
                num_epochs=int(cfg.training.num_epochs),
                batch_size=int(cfg.training.batch_size),
                early_stopping_patience=int(cfg.training.early_stopping_patience),
                early_stopping_min_delta=float(cfg.training.early_stopping_min_delta),
                random_seed=2024,
            )

            with mlflow.start_run(run_name=f"trial_{trial_idx}", nested=True):
                mlflow.log_params({k: (str(v) if v is None else v) for k, v in hparams.items()})

                metrics = train_and_evaluate(train_dataset, val_dataset, gene_names, train_cfg, device)

                mlflow.log_metrics({
                    "mean_pearson": metrics["mean_pearson"],
                    "median_pearson": metrics["median_pearson"],
                })
                for step, loss in enumerate(metrics["train_loss_curve"]):
                    mlflow.log_metric("train_loss", loss, step=step)
                for step, loss in enumerate(metrics["val_loss_curve"]):
                    mlflow.log_metric("val_loss", loss, step=step)

            row: dict[str, Any] = {
                "trial_idx": trial_idx, **hparams,
                "mean_pearson": metrics["mean_pearson"],
                "median_pearson": metrics["median_pearson"],
            }
            trial_rows.append(row)

            if best_trial is None or (
                not np.isnan(metrics["mean_pearson"])
                and metrics["mean_pearson"] > best_trial["mean_pearson"]
            ):
                best_trial = {**row, **metrics}

            print(f"[experiment] Trial {trial_idx + 1}/{len(grid)} — "
                  f"mean_pearson={metrics['mean_pearson']:.4f} median_pearson={metrics['median_pearson']:.4f}")

    # ── save results ─────────────────────────────────────────────────────────
    pd.DataFrame(trial_rows).to_csv(output_dir / "grid_search_results.csv", index=False)

    assert best_trial is not None
    np.save(output_dir / "best_train_loss_curve.npy", np.array(best_trial["train_loss_curve"]))
    np.save(output_dir / "best_val_loss_curve.npy", np.array(best_trial["val_loss_curve"]))
    _plot_training_curve(
        best_trial["train_loss_curve"], best_trial["val_loss_curve"],
        output_dir / "best_training_curve.png",
    )
    _plot_pearson_distribution(best_trial["per_gene_pearson"], output_dir / "pearson_distribution.png")

    per_gene = pd.Series(best_trial["per_gene_pearson"], name="pearson").sort_values(ascending=False)
    per_gene.dropna().head(10).to_csv(output_dir / "top10_genes.csv", header=True)
    per_gene.dropna().tail(10).to_csv(output_dir / "worst10_genes.csv", header=True)

    # Post-hoc reporting only — no retraining, no further HVG computation (see
    # _gene_interval_stats docstring): mean/median Pearson restricted to the top-N most variable
    # genes of the trained num_genes set, for each N in cfg.data.gene_interval.
    gene_interval = list(cfg.data.gene_interval)
    gene_interval_stats = _gene_interval_stats(genes_table, best_trial["per_gene_pearson"], gene_interval)
    gene_interval_stats.to_csv(output_dir / "gene_interval_stats.csv", index=False)
    _plot_gene_interval_stats(gene_interval_stats, output_dir / "gene_interval_stats.png")

    hparam_keys = [k for k in best_trial.keys() if k in grid[0].keys()]
    summary = {
        "best_config": {k: best_trial[k] for k in hparam_keys},
        "best_metrics": {
            "mean_pearson": best_trial["mean_pearson"],
            "median_pearson": best_trial["median_pearson"],
        },
        "num_genes": num_genes,
        "n_neighbors": int(cfg.data.n_neighbors),
        "gene_interval_stats": gene_interval_stats.to_dict(orient="records"),
        "all_trial_results": trial_rows,
    }
    with open(output_dir / "results_summary.yaml", "w") as f:
        yaml.dump(summary, f, default_flow_style=False)

    print(f"[experiment] Done. Best mean_pearson={best_trial['mean_pearson']:.4f} "
          f"with config {summary['best_config']}")


# ── Hydra entry point ─────────────────────────────────────────────────────────

@hydra.main(config_path="../../../configs", config_name="deepspot_train", version_base="1.3")
def main(cfg: DictConfig) -> None:
    split_idx: Optional[int] = OmegaConf.select(cfg, "split_idx")
    if split_idx is None:
        print(
            "ERROR: split_idx is required. Pass split_idx=<N> (or split_idx=-1 for same_wsi_split).",
            file=sys.stderr,
        )
        sys.exit(1)

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"[experiment] device={device}, split_idx={split_idx}")

    repo_root = Path(hydra.utils.get_original_cwd())
    outputs_folder_name: str = str(OmegaConf.select(cfg, "output_dir", default="outputs_deepspot"))
    split_label = "same_wsi_split" if split_idx == -1 else f"split_{split_idx}"
    consider_matching: bool = bool(OmegaConf.select(cfg, "data.consider_matching", default=True))
    embeddings_datasets: list[str] = list(cfg.data.embeddings_datasets) if cfg.data.embeddings_datasets else []
    output_dir = (
        repo_root / outputs_folder_name
        / cfg.data.model_name / cfg.data.correction_name
        / _matching_folder_name(consider_matching)
        / _embeddings_folder_name(embeddings_datasets)
        / str(int(cfg.data.num_genes))
        / str(int(cfg.data.n_neighbors))
        / split_label
    )

    run_split_experiment(split_idx, cfg, device, output_dir)


if __name__ == "__main__":
    main()
