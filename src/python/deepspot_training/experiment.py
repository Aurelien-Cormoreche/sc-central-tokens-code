"""
Layer 2 — Experiment runner for one train/val split.

`num_genes` and `n_neighbors` are fixed per run (part of `data:`, not swept) so the expensive I/O
(adata + embeddings loading, neighbor-graph construction) happens exactly once per split. The grid
search sweeps only model/training hyperparameters (learning_rate, dropout, loss_func, weight_decay,
gene_normalization, ...) on top of that single preloaded dataset pair, mirroring
classifier_training/experiment.py's "preload once, share across trials" pattern.

Invoked by the SLURM jobs generated by launcher.py:
    python -m src.python.deepspot_training.experiment \
        split_idx=0 data.model_name=virchow_v2 data.correction_name=scanorama
"""
